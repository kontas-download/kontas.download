'use client';

import React, { useState } from 'react';
import { AlertCircle, Copy, KeyRound, Plus, Trash2, UserCog, X } from 'lucide-react';
import { useI18n } from '@/lib/i18n/client';

export interface UserRow { id: number; email: string; name: string; role: string; disabled: boolean; lastAction: string | null; lastActionAt: string | null }
type Dialog = { kind: 'create' } | { kind: 'edit'; user: UserRow } | { kind: 'reset'; user: UserRow } | null;

const input = 'w-full px-3 py-2 rounded-lg border border-slate-300 text-sm focus:outline-none focus:ring-2 focus:ring-emerald-500';
const label = 'block text-xs font-semibold text-slate-700 mb-1';
const linkButton = 'text-xs font-semibold text-emerald-700 underline disabled:opacity-50';

async function send(url: string, method: string, body?: unknown) {
  const res = await fetch(url, { method, headers: { 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || String(res.status));
  return data;
}

// A password generated by the server, shown once with a copy button.
function GeneratedPassword({ password }: { password: string }) {
  const { t } = useI18n();
  const [copied, setCopied] = useState(false);
  return (
    <div className="mt-4 p-3 rounded-lg bg-amber-50 border border-amber-200 text-sm">
      <div className="font-semibold text-amber-900">{t('users.generatedTitle')}</div>
      <div className="mt-2 flex items-center gap-2">
        <code className="flex-1 bg-white border border-amber-200 rounded px-2 py-1 font-mono select-all break-all" data-testid="generated-password">{password}</code>
        <button type="button" onClick={() => navigator.clipboard?.writeText(password).then(() => setCopied(true)).catch(() => setCopied(false))} className="inline-flex items-center gap-1 px-2 py-1 rounded border border-amber-300 text-xs">
          <Copy className="w-3.5 h-3.5" />{copied ? t('users.copied') : t('users.copy')}
        </button>
      </div>
      <p className="mt-2 text-xs text-amber-800">{t('users.generatedHint')}</p>
    </div>
  );
}

function PasswordFields({ generate, setGenerate, password, setPassword }: { generate: boolean; setGenerate: (v: boolean) => void; password: string; setPassword: (v: string) => void }) {
  const { t } = useI18n();
  return (
    <div className="space-y-2">
      <label className="flex items-center gap-2 text-xs text-slate-700"><input type="checkbox" checked={generate} onChange={e => setGenerate(e.target.checked)} />{t('users.generatePassword')}</label>
      {!generate && (
        <label className="block">
          <span className={label}>{t('users.password')}</span>
          <input type="password" autoComplete="new-password" required minLength={10} maxLength={1024} value={password} onChange={e => setPassword(e.target.value)} className={input} />
          <span className="text-[11px] text-slate-500">{t('users.passwordHint')}</span>
        </label>
      )}
    </div>
  );
}

export function UsersClient({ initialUsers, currentUserId }: { initialUsers: UserRow[]; currentUserId: number }) {
  const { t, lang } = useI18n();
  const [users, setUsers] = useState<UserRow[]>(initialUsers);
  const [dialog, setDialog] = useState<Dialog>(null);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');
  const [busy, setBusy] = useState(false);
  const [generated, setGenerated] = useState('');
  const [form, setForm] = useState({ name: '', email: '', role: 'accountant', password: '', generate: true });

  const reload = async () => {
    try { setUsers((await send('/api/users', 'GET')).users); } catch { setError(t('users.loadError')); }
  };
  const open = (next: Dialog) => {
    setError(''); setNotice(''); setGenerated('');
    setForm(next && next.kind === 'edit' ? { name: next.user.name, email: next.user.email, role: next.user.role, password: '', generate: true } : { name: '', email: '', role: 'accountant', password: '', generate: true });
    setDialog(next);
  };
  const run = async (action: () => Promise<void>) => {
    setBusy(true); setError(''); setNotice('');
    try { await action(); await reload(); } catch (e) { setError(e instanceof Error ? e.message : t('users.saveError')); } finally { setBusy(false); }
  };
  const passwordBody = () => form.generate ? { generatePassword: true } : { password: form.password };

  const submit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!dialog) return;
    run(async () => {
      if (dialog.kind === 'create') {
        const data = await send('/api/users', 'POST', { name: form.name, email: form.email, role: form.role, ...passwordBody() });
        if (data.password) setGenerated(data.password); else setDialog(null);
      } else if (dialog.kind === 'edit') {
        await send(`/api/users/${dialog.user.id}`, 'PATCH', { name: form.name, role: form.role });
        setDialog(null);
      } else {
        const data = await send(`/api/users/${dialog.user.id}`, 'PATCH', passwordBody());
        if (data.password) setGenerated(data.password); else { setDialog(null); setNotice(t('users.resetDone')); }
      }
    });
  };
  const toggle = (user: UserRow) => {
    if (!user.disabled && !confirm(t('users.disableConfirm', { name: user.name }))) return;
    run(async () => { await send(`/api/users/${user.id}`, 'PATCH', { disabled: !user.disabled }); });
  };
  const remove = (user: UserRow) => {
    if (!confirm(t('users.deleteConfirm', { name: user.name }))) return;
    run(async () => { const data = await send(`/api/users/${user.id}`, 'DELETE'); if (!data.deleted) setNotice(t('users.disabledInstead')); });
  };
  const roleName = (role: string) => role === 'admin' ? t('users.roleAdmin') : role === 'accountant' ? t('users.roleAccountant') : role;
  const when = (iso: string | null) => iso ? new Date(iso.includes('T') ? iso : iso.replace(' ', 'T') + 'Z').toLocaleString(lang) : '';

  return (
    <div className="p-8 max-w-7xl mx-auto space-y-6">
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 flex items-center gap-2.5"><UserCog className="w-7 h-7 text-emerald-600" /><span>{t('users.title')}</span></h1>
          <p className="text-sm text-slate-500 mt-1">{t('users.subtitle')}</p>
        </div>
        <button onClick={() => open({ kind: 'create' })} className="inline-flex items-center gap-2 px-4 py-2.5 rounded-lg bg-emerald-600 hover:bg-emerald-700 text-white font-medium text-sm shadow-sm">
          <Plus className="w-4 h-4" /><span>{t('users.create')}</span>
        </button>
      </div>

      {!dialog && error && <div className="p-3 rounded-lg bg-rose-50 text-rose-700 text-sm flex items-center gap-2"><AlertCircle className="w-4 h-4 shrink-0" />{error}</div>}
      {notice && <div className="p-3 rounded-lg bg-emerald-50 text-emerald-800 text-sm">{notice}</div>}

      <div className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-x-auto">
        <table className="w-full text-sm">
          <thead className="bg-slate-50 text-xs text-slate-500 text-left">
            <tr><th className="p-3">{t('users.name')}</th><th className="p-3">{t('users.email')}</th><th className="p-3">{t('users.role')}</th><th className="p-3">{t('users.status')}</th><th className="p-3">{t('users.lastAction')}</th><th className="p-3">{t('common.actions')}</th></tr>
          </thead>
          <tbody>
            {users.map(user => (
              <tr key={user.id} className={`border-t border-slate-100 ${user.disabled ? 'text-slate-400' : ''}`}>
                <td className="p-3 font-semibold">{user.name}{user.id === currentUserId && <span className="ml-1 text-xs font-normal text-slate-500">({t('users.you')})</span>}</td>
                <td className="p-3">{user.email}</td>
                <td className="p-3">{roleName(user.role)}</td>
                <td className="p-3"><span className={`px-2 py-0.5 rounded-full text-xs font-semibold ${user.disabled ? 'bg-slate-100 text-slate-500' : 'bg-emerald-100 text-emerald-800'}`}>{user.disabled ? t('users.disabled') : t('users.active')}</span></td>
                <td className="p-3 text-xs">{user.lastAction ? <>{t('users.action' + user.lastAction)}<div className="text-slate-500">{when(user.lastActionAt)}</div></> : t('users.never')}</td>
                <td className="p-3">
                  <div className="flex flex-wrap items-center gap-3">
                    <button disabled={busy} onClick={() => open({ kind: 'edit', user })} className={linkButton}>{t('common.edit')}</button>
                    <button disabled={busy} onClick={() => open({ kind: 'reset', user })} className={linkButton}>{t('users.resetPassword')}</button>
                    <button disabled={busy} onClick={() => toggle(user)} className={linkButton}>{user.disabled ? t('users.enable') : t('users.disable')}</button>
                    <button disabled={busy} onClick={() => remove(user)} title={t('common.delete')} className="p-1 rounded text-slate-400 hover:text-rose-600 hover:bg-rose-50"><Trash2 className="w-4 h-4" /></button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {dialog && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/60 backdrop-blur-sm" role="dialog" aria-modal="true">
          <div className="bg-white rounded-2xl max-w-lg w-full p-6 shadow-2xl border border-slate-200">
            <div className="flex items-center justify-between pb-4 border-b border-slate-100">
              <h3 className="text-lg font-bold text-slate-900 flex items-center gap-2">
                {dialog.kind === 'reset' ? <KeyRound className="w-5 h-5 text-emerald-600" /> : <UserCog className="w-5 h-5 text-emerald-600" />}
                <span>{dialog.kind === 'create' ? t('users.create') : dialog.kind === 'edit' ? t('users.editTitle') : t('users.resetTitle', { name: dialog.user.name })}</span>
              </h3>
              <button onClick={() => setDialog(null)} className="p-1 rounded-lg text-slate-400 hover:bg-slate-100" title={t('common.close')}><X className="w-5 h-5" /></button>
            </div>
            {error && <div className="mt-4 p-3 rounded-lg bg-rose-50 text-rose-700 text-xs flex items-center gap-2"><AlertCircle className="w-4 h-4 shrink-0" />{error}</div>}
            {generated ? (
              <>
                <GeneratedPassword password={generated} />
                <div className="pt-4 flex justify-end"><button onClick={() => setDialog(null)} className="px-4 py-2 rounded-lg bg-emerald-600 text-white text-sm font-medium">{t('common.close')}</button></div>
              </>
            ) : (
              <form onSubmit={submit} className="mt-4 space-y-4">
                {dialog.kind !== 'reset' && (
                  <>
                    <label className="block"><span className={label}>{t('users.name')}</span><input required maxLength={200} value={form.name} onChange={e => setForm({ ...form, name: e.target.value })} className={input} /></label>
                    <label className="block"><span className={label}>{t('users.email')}</span><input type="email" required maxLength={254} disabled={dialog.kind === 'edit'} value={form.email} onChange={e => setForm({ ...form, email: e.target.value })} className={input} /></label>
                    <label className="block"><span className={label}>{t('users.role')}</span>
                      <select value={form.role} onChange={e => setForm({ ...form, role: e.target.value })} className={input}>
                        <option value="accountant">{t('users.roleAccountant')}</option>
                        <option value="admin">{t('users.roleAdmin')}</option>
                      </select>
                      <span className="text-[11px] text-slate-500">{t('users.roleHint')}</span>
                    </label>
                  </>
                )}
                {dialog.kind !== 'edit' && <PasswordFields generate={form.generate} setGenerate={v => setForm({ ...form, generate: v })} password={form.password} setPassword={v => setForm({ ...form, password: v })} />}
                <div className="pt-2 flex justify-end gap-2">
                  <button type="button" onClick={() => setDialog(null)} className="px-4 py-2 rounded-lg border border-slate-300 text-sm">{t('common.cancel')}</button>
                  <button type="submit" disabled={busy} className="px-4 py-2 rounded-lg bg-emerald-600 hover:bg-emerald-700 text-white text-sm font-medium disabled:opacity-50">{t('common.save')}</button>
                </div>
              </form>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
